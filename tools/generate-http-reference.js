"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const files = ["bridge.js", ...fs.readdirSync(path.join(root, "server")).filter(n => n.endsWith("-routes.js"))].sort();
const labels = { clipboard: "Quick Copy Settings / Paste Settings", export: "Export… / Export with Previous", history: "Undo / Redo",
    masking: "Masking", remove: "Healing / Distraction Removal", reflections: "Reflections", people: "People", "red-eye": "Red Eye",
    "lens-blur": "Lens Blur (SDK and Windows)", "develop-categorical": "Develop / Profiles (Windows inventory)",
    "develop-presets": "Develop Presets", "tone-curve": "Tone Curve", "point-curve": "Tone Curve", "point-color": "Point Color", "color-grading": "Color Grading", enhance: "Enhance" };
const ordinary = new Set(["/command", "/set", "/adjust", "/reset", "/action"]);
const internal = new Set(["/context/update", "/tone-curve/feedback", "/develop-presets/inventory/item",
    "/develop-presets/inventory/complete", "/develop-presets/inventory/fail", "/remove/selection-native",
    "/remove/selection-refinement-native", "/remove/selection-validate", "/remove/selection-guard"]);
const reads = new Set(["/color-grading", "/get", "/last-result", "/feedback/all", "/feedback/value", "/masking/presets"]);
function kind(p) {
    if (["/diagnostics/masking-deletion-browser", "/diagnostics/masking-preset-trace"].includes(p)) return "internal";
    if (internal.has(p) || /(?:\/next|\/result|[-/]result|\/claim|\/validate|\/validation|\/profile-feedback|\/profile-validation)$/.test(p) && p !== "/last-result") return "internal";
    if (["/wake-lightroom", "/lens-blur/depth-visualization/toggle"].includes(p)) return "deprecated";
    if (ordinary.has(p)) return "ordinary";
    if (reads.has(p) || /\/(?:state|snapshot|status|sliders|groups|help|context|capabilities|inventory|list|metadata|request|request-all|request-many)$/.test(p) || p === "/" || p.includes("/diagnostics/")) return "read";
    return "workflow";
}
const operations = [];
for (const file of files) {
    const source = fs.readFileSync(path.join(root, "server", file), "utf8");
    for (const match of source.matchAll(/app\.(get|post)\(\s*["']([^"']+)["']\s*,/g)) {
        const route = match[2], prefix = route.split("/")[1];
        operations.push({ method: match[1].toUpperCase(), path: route, group: labels[prefix] || "Core / " + (prefix || "status"),
            kind: kind(route), source: "server/" + file, line: source.slice(0, match.index).split("\n").length });
    }
    // Expand the existing string-enum route family instead of indexing its incomplete prefix.
    for (const match of source.matchAll(/(\[[^\]\n]+\])\.forEach\(function \((\w+)\) \{\s*app\.(get|post)\(["']([^"']+)["'] \+ \2,/g)) {
        const values = JSON.parse(match[1]);
        for (const value of values) {
            const route=match[4]+value, prefix=route.split("/")[1];
            operations.push({method:match[3].toUpperCase(),path:route,group:labels[prefix] || "Core / "+prefix,
                kind:kind(route),source:"server/"+file,line:source.slice(0,match.index).split("\n").length+1});
        }
    }
}
operations.sort((a,b) => a.group.localeCompare(b.group) || a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
const notes = { ordinary: "Ordinary Builder commands use these routes with validated parameters. Acceptance means queued, not confirmed Lightroom execution; a route alone is not a complete command.",
    read: "State/discovery. Some reads request asynchronous SDK feedback; observe availability and freshness.",
    workflow: "Not generated as a permanent URL. Use the controller or documented multi-step workflow with exact parameters, context, gesture lifecycle and results.",
    internal: "Internal plug-in protocol. Not a controller action or reusable URL.", deprecated: "Legacy/unsupported entry; use the current controller workflow." };
const data = { version: 1, workflows: "/reference/HTTP_WORKFLOWS.md", notes, operations };
const md = ["# HTTP operation inventory", "", "Generated by `npm run generate:http-reference` from registered server routes. Paths are route identifiers, **not complete or permanently reusable commands**. This table is an index, not an executable example. Parameterized route segments use `:name`.", "", "Use these paths directly on port **17891**; prepend `/api` only for the Web Controller proxy on port **17892**. See [Builder parameters and workflow requirements](HTTP_WORKFLOWS.md). Internal routes are recorded for completeness, not offered as actions. HTTP acceptance is not confirmed Lightroom execution.", "", ...Object.entries(notes).map(([k,v]) => "- **"+k+"**: "+v), "", "| Group | Method / path | Support | Source |", "|---|---|---|---|",
    ...operations.map(o => `| ${o.group} | ${o.method} \`${o.path}\` | ${o.kind} | ${o.source}:${o.line} |`), ""].join("\n");
for (const [file, text] of [["server/http-operations.json", JSON.stringify(data, null, 2)+"\n"], ["docs/HTTP_OPERATIONS.md", md]]) {
    const target = path.join(root,file);
    if (process.argv.includes("--check")) {
        if (!fs.existsSync(target) || fs.readFileSync(target,"utf8") !== text) throw Error("Regenerate " + file);
    } else fs.writeFileSync(target,text);
}
console.log("HTTP inventory: " + operations.length + " registered routes; guarded workflows explicitly distinguished.");
